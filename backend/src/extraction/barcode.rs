//! Barcode and Patch Code separator sheet engine for high-volume batch scanning.
//!
//! Provides Code 128 / Code 39 checksum verification, standard Kodak/Fujitsu Patch Code
//! recognition (Patch 1, 2, 3, 4, 6, and Patch T), and multi-document splitting algorithms
//! for ADF scanner feeds and enterprise IDP ingestion pipelines.

use serde::{Deserialize, Serialize};

/// Type of barcode or separator detected on a document page.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum BarcodeType {
    Code128,
    Code39,
    QrCode,
    DataMatrix,
    PatchCode,
    Unknown,
}

/// Standard Patch Code types used by production document scanners (Kodak, Fujitsu, Canon).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum PatchCodeType {
    /// Patch 1: Document separator (does not split file, increments doc counter)
    Patch1,
    /// Patch 2: Document separator (assigns distinct document type)
    Patch2,
    /// Patch 3: Batch header separator
    Patch3,
    /// Patch 4: Color dropout toggle
    Patch4,
    /// Patch 6: Sub-batch separator
    Patch6,
    /// Patch T (Transfer): Separates documents and initiates new file
    PatchT,
}

impl PatchCodeType {
    pub fn as_str(&self) -> &'static str {
        match self {
            Self::Patch1 => "PATCH-1",
            Self::Patch2 => "PATCH-2",
            Self::Patch3 => "PATCH-3",
            Self::Patch4 => "PATCH-4",
            Self::Patch6 => "PATCH-6",
            Self::PatchT => "PATCH-T",
        }
    }

    pub fn from_str_loose(s: &str) -> Option<Self> {
        let upper = s.trim().to_uppercase();
        match upper.as_str() {
            "PATCH 1" | "PATCH-1" | "PATCH1" => Some(Self::Patch1),
            "PATCH 2" | "PATCH-2" | "PATCH2" => Some(Self::Patch2),
            "PATCH 3" | "PATCH-3" | "PATCH3" => Some(Self::Patch3),
            "PATCH 4" | "PATCH-4" | "PATCH4" => Some(Self::Patch4),
            "PATCH 6" | "PATCH-6" | "PATCH6" => Some(Self::Patch6),
            "PATCH T" | "PATCH-T" | "PATCHT" | "PATCH-TRANSFER" => Some(Self::PatchT),
            _ => None,
        }
    }
}

/// Information about a detected barcode on a document page.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct DetectedBarcode {
    pub barcode_type: BarcodeType,
    pub raw_data: String,
    pub page_number: usize,
    pub confidence: f64,
    pub bbox: Option<[f64; 4]>,
    pub is_separator: bool,
}

/// A logical document split result generated by scanning separator sheets.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct DocumentSplitSegment {
    pub document_index: usize,
    pub start_page: usize,
    pub end_page: usize,
    pub page_count: usize,
    pub separator_barcode: Option<String>,
    pub metadata_tags: Vec<String>,
}

/// Computes the Code 39 Mod-43 checksum character for a given string.
pub fn calculate_code39_mod43(data: &str) -> Option<char> {
    const CHARSET: &[u8] = b"0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ-. $/+%";

    let upper = data.to_ascii_uppercase();
    let mut sum: usize = 0;

    for b in upper.bytes() {
        if let Some(pos) = CHARSET.iter().position(|&c| c == b) {
            sum += pos;
        } else {
            return None; // Invalid Code 39 character
        }
    }

    let remainder = sum % 43;
    Some(CHARSET[remainder] as char)
}

/// Verifies whether a Code 39 string with an appended checksum is valid.
pub fn verify_code39_checksum(data_with_checksum: &str) -> bool {
    let clean = data_with_checksum.trim().trim_matches('*');
    if clean.len() < 2 {
        return false;
    }

    let (payload, check_char_str) = clean.split_at(clean.len() - 1);
    let check_char = check_char_str.chars().next().unwrap();

    if let Some(expected) = calculate_code39_mod43(payload) {
        expected.to_ascii_uppercase() == check_char.to_ascii_uppercase()
    } else {
        false
    }
}

/// Verifies the Code 128 (Subset B) checksum for a sequence of character values.
pub fn verify_code128_subset_b(data: &str, checksum_value: u32) -> bool {
    // Start B character has value 104
    let mut sum: u32 = 104;

    for (idx, ch) in data.bytes().enumerate() {
        // In Code 128 subset B, ASCII 32 to 127 maps to values 0 to 95
        if ch >= 32 && ch <= 127 {
            let val = (ch - 32) as u32;
            let weight = (idx + 1) as u32;
            sum += val * weight;
        } else {
            return false;
        }
    }

    (sum % 103) == checksum_value
}

/// Inspects a stream of scanned pages with detected barcodes and splits them
/// into separate logical document segments whenever a separator sheet (Patch Code or custom delimiter) is encountered.
pub fn split_scanned_batch(
    total_pages: usize,
    detected_barcodes: &[DetectedBarcode],
    discard_separator_sheets: bool,
) -> Vec<DocumentSplitSegment> {
    if total_pages == 0 {
        return Vec::new();
    }

    // Group barcodes by page number
    let mut separator_pages = Vec::new();

    for bc in detected_barcodes {
        let is_sep = bc.is_separator
            || bc.barcode_type == BarcodeType::PatchCode
            || PatchCodeType::from_str_loose(&bc.raw_data).is_some()
            || bc.raw_data.to_uppercase().starts_with("FILEDECK-SEP-")
            || bc.raw_data.to_uppercase().starts_with("DOC-START");

        if is_sep && !separator_pages.iter().any(|(p, _)| *p == bc.page_number) {
            separator_pages.push((bc.page_number, bc.raw_data.clone()));
        }
    }

    separator_pages.sort_by_key(|(p, _)| *p);

    let mut segments = Vec::new();
    let mut current_doc_idx = 1;
    let mut current_start = 1;

    for (sep_page, sep_data) in separator_pages {
        if sep_page > current_start {
            let end_page = if discard_separator_sheets {
                sep_page - 1
            } else {
                sep_page - 1
            };

            segments.push(DocumentSplitSegment {
                document_index: current_doc_idx,
                start_page: current_start,
                end_page,
                page_count: end_page.saturating_sub(current_start) + 1,
                separator_barcode: Some(sep_data.clone()),
                metadata_tags: vec![format!("barcode:{}", sep_data)],
            });
            current_doc_idx += 1;
        }

        current_start = if discard_separator_sheets {
            sep_page + 1
        } else {
            sep_page
        };
    }

    // Trailing document segment
    if current_start <= total_pages {
        segments.push(DocumentSplitSegment {
            document_index: current_doc_idx,
            start_page: current_start,
            end_page: total_pages,
            page_count: total_pages.saturating_sub(current_start) + 1,
            separator_barcode: None,
            metadata_tags: Vec::new(),
        });
    }

    segments
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_code39_checksum_calculation() {
        // Standard test vector: "CODE39"
        let check = calculate_code39_mod43("CODE39");
        assert!(check.is_some());
        let full = format!("CODE39{}", check.unwrap());
        assert!(verify_code39_checksum(&full));
        assert!(!verify_code39_checksum("CODE39Z"));
    }

    #[test]
    fn test_patch_code_identification() {
        assert_eq!(PatchCodeType::from_str_loose("PATCH T"), Some(PatchCodeType::PatchT));
        assert_eq!(PatchCodeType::from_str_loose("patch-t"), Some(PatchCodeType::PatchT));
        assert_eq!(PatchCodeType::from_str_loose("Patch 2"), Some(PatchCodeType::Patch2));
        assert_eq!(PatchCodeType::from_str_loose("Random Text"), None);
    }

    #[test]
    fn test_batch_splitting() {
        let total_pages = 10;
        let barcodes = vec![
            DetectedBarcode {
                barcode_type: BarcodeType::PatchCode,
                raw_data: "PATCH-T".to_string(),
                page_number: 4,
                confidence: 0.99,
                bbox: Some([0.1, 0.4, 0.2, 0.6]),
                is_separator: true,
            },
            DetectedBarcode {
                barcode_type: BarcodeType::Code128,
                raw_data: "FILEDECK-SEP-INVOICE".to_string(),
                page_number: 8,
                confidence: 0.99,
                bbox: Some([0.1, 0.4, 0.2, 0.6]),
                is_separator: true,
            },
        ];

        let splits = split_scanned_batch(total_pages, &barcodes, true);
        assert_eq!(splits.len(), 3);

        // Doc 1: Pages 1-3
        assert_eq!(splits[0].document_index, 1);
        assert_eq!(splits[0].start_page, 1);
        assert_eq!(splits[0].end_page, 3);
        assert_eq!(splits[0].page_count, 3);

        // Doc 2: Pages 5-7 (Page 4 separator discarded)
        assert_eq!(splits[1].document_index, 2);
        assert_eq!(splits[1].start_page, 5);
        assert_eq!(splits[1].end_page, 7);
        assert_eq!(splits[1].page_count, 3);

        // Doc 3: Pages 9-10 (Page 8 separator discarded)
        assert_eq!(splits[2].document_index, 3);
        assert_eq!(splits[2].start_page, 9);
        assert_eq!(splits[2].end_page, 10);
        assert_eq!(splits[2].page_count, 2);
    }
}
